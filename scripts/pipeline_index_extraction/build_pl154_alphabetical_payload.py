def main() -> None:
    ap = argparse.ArgumentParser(description="Build the PL154 alphabetical payload and helper request.")
    ap.add_argument("--write-helper-request", action="store_true", help="Write the helper request JSON and exit.")
    ap.add_argument("--build-payload", action="store_true", help="Build the final payload JSON.")
    ap.add_argument("--helper-request-json", type=Path, required=True)
    ap.add_argument("--helper-output-json", type=Path, default=ROOT / "data/alphabetical_index_payloads/PL154_helper_output.json")
    ap.add_argument("--intermediate-dir", type=Path, required=True)
    ap.add_argument("--output-file", type=Path, default=ROOT / "data/alphabetical_index_payloads/PL154_alphabetical_indices.json")
    args = ap.parse_args()

    if args.write_helper_request:
        write_json(args.helper_request_json, build_helper_request())
        todo = {
            "volume_id": VOLUME_ID,
            "updated_at": now_iso(),
            "current_focus": "Generate helper output for PL154 and assemble the final alphabetical payload.",
            "completed": [
                "OCR tail inspected",
                "opening ELENCHUS and closing ORDO RERUM sections identified",
            ],
            "pending": [
                "run index_target_locator on the helper request",
                "build the final JSON payload from OCR and helper evidence",
            ],
            "blocked": [],
            "notes": [
                "Keep the ELENCHUS author index separate from the volume-end ORDO RERUM table.",
                "Preserve column/page distinction for the Chronicon entry in the ELENCHUS.",
            ],
        }
        write_json(args.intermediate_dir / "todo.json", todo)
        return

    if args.build_payload:
        payload = build_payload(args.helper_output_json, args.intermediate_dir)
        write_json(args.output_file, payload)
        return

    raise SystemExit("Specify either --write-helper-request or --build-payload.")


if __name__ == "__main__":
    main()
