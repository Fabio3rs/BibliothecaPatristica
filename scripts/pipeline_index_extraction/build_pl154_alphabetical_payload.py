        if helper_entry_id in TARGET_FILE_NULLS:
            target_file_best = None
        raw_json = {
            "source_line": row["entry_raw"],
            "section_kind": "author_index" if row["section_key"] == SECTION_1_KEY else "ordo_rerum",
        }
        raw_note = row.get("raw_note")
        if raw_note:
            raw_json["note"] = raw_note
        if helper_entry:
            raw_json.update(helper_summary(helper_entry))
            raw_json["helper_entry_id"] = row["helper_entry_id"]
            raw_json["helper_used"] = True
            if helper_entry_id in TARGET_FILE_OVERRIDES:
                raw_json["target_file_override"] = target_file_best
