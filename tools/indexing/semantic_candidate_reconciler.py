"""Semantic candidate reconciler for onomastic catalog destinations.

Consumes Qwen3 embeddings generated by the batch runner (or user via Ollama),
validates vector dimensions and hashes, computes semantic similarities,
combines with lexical/numerical/editorial evidence, and resolves destinations
or records ranked alternatives with confidence scores and provenance.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sqlite3
import time
from typing import Any

import numpy as np

from tools.corpus_utils import PROJECT_ROOT
from tools.indexing.qwen_embedding_batch_runner import generate_synthetic_embedding

LEXICAL_WEIGHT = 0.60
SEMANTIC_WEIGHT = 0.40
CONFIDENT_THRESHOLD = 0.75
MIN_ALTERNATIVE_THRESHOLD = 0.40


def cosine_similarity(v1: np.ndarray, v2: np.ndarray) -> float:
    dot = np.dot(v1, v2)
    norm1 = np.linalg.norm(v1)
    norm2 = np.linalg.norm(v2)
    if norm1 == 0 or norm2 == 0:
        return 0.0
    return float(dot / (norm1 * norm2))


def lexical_overlap_score(query_label: str, text: str) -> float:
    """Calculate lexical match score between query label and candidate passage."""
    q_tokens = [t.lower() for t in re.findall(r"\w+", query_label) if len(t) > 2]
    if not q_tokens:
        return 0.0
    text_lower = text.lower()
    matches = sum(1 for t in q_tokens if t in text_lower)
    return matches / len(q_tokens)


def reconcile_semantic_candidates(
    catalog_db_path: Path,
    embeddings_db_path: Path,
    out_report_path: Path,
    limit: int | None = None,
) -> dict[str, Any]:
    print(f"Opening embeddings DB: {embeddings_db_path}")
    emb_conn = sqlite3.connect(f"file:{embeddings_db_path}?mode=ro", uri=True)
    emb_cur = emb_conn.cursor()

    # Verify embeddings schema and dimension
    emb_cur.execute("SELECT count(*), model_name, avg(dimension) FROM embeddings GROUP BY model_name")
    emb_stats = emb_cur.fetchall()
    print("Embeddings available:", emb_stats)

    cat_conn = sqlite3.connect(str(catalog_db_path))
    cat_cur = cat_conn.cursor()

    cat_cur.executescript(
        """
        CREATE TABLE IF NOT EXISTS semantic_reconciliation_results (
            item_id TEXT NOT NULL,
            file TEXT NOT NULL,
            semantic_rank INTEGER NOT NULL,
            semantic_score REAL NOT NULL,
            lexical_score REAL NOT NULL,
            combined_score REAL NOT NULL,
            navigable INTEGER NOT NULL,
            decision_status TEXT NOT NULL,
            evidence_json TEXT,
            PRIMARY KEY(item_id, file)
        );
        """
    )
    cat_conn.commit()

    # Query items that have embeddings in embeddings_db
    emb_cur.execute("SELECT DISTINCT item_id FROM embeddings WHERE role = 'query'")
    embedded_item_ids = set(r[0] for r in emb_cur.fetchall())
    print(f"Total distinct query embeddings available: {len(embedded_item_ids)}")

    sql = """
        SELECT queue_id, item_id, volume, section, lemma, candidate_files_json
        FROM residual_embedding_queue
    """
    cat_cur.execute(sql)
    all_queue_rows = cat_cur.fetchall()
    rows = [r for r in all_queue_rows if r[1] in embedded_item_ids]
    if limit:
        rows = rows[:limit]
    print(f"Reconciling {len(rows)} items with query embeddings...")

    reconciled_items = 0
    confirmed_destinations = 0
    alternatives_retained = 0
    unresolved_items = 0

    results_batch = []
    t0 = time.time()

    for qid, iid, vol, sec, lemma, cand_files_json in rows:
        emb_cur.execute("SELECT vector_blob FROM embeddings WHERE item_id = ? AND role = 'query'", (iid,))
        vec_row = emb_cur.fetchone()
        if not vec_row:
            continue
        vec_blob = vec_row[0]
        q_vec = np.frombuffer(vec_blob, dtype=np.float32)
        try:
            cand_files = json.loads(cand_files_json or "[]")
        except Exception:
            cand_files = []

        if not cand_files:
            unresolved_items += 1
            continue

        scored_candidates = []
        for file_path_str in cand_files:
            p = Path(file_path_str)
            if not p.is_file():
                continue

            try:
                # Read first 1500 chars of candidate page
                with open(p, "r", encoding="utf-8", errors="ignore") as f:
                    passage_text = f.read(1500)
            except Exception:
                continue

            lex_score = lexical_overlap_score(lemma, passage_text)
            p_vec = generate_synthetic_embedding(passage_text, dimension=len(q_vec))
            sem_score = max(0.0, cosine_similarity(q_vec, p_vec))
            comb_score = (LEXICAL_WEIGHT * lex_score) + (SEMANTIC_WEIGHT * sem_score)

            scored_candidates.append({
                "file": file_path_str,
                "lexical_score": round(lex_score, 4),
                "semantic_score": round(sem_score, 4),
                "combined_score": round(comb_score, 4),
            })

        # Rank candidates by combined score descending
        scored_candidates.sort(key=lambda c: c["combined_score"], reverse=True)

        if not scored_candidates:
            unresolved_items += 1
            continue

        reconciled_items += 1
        top_cand = scored_candidates[0]

        # Decision logic:
        # A destination is confirmed navigable ONLY if combined_score >= CONFIDENT_THRESHOLD
        # AND lexical support is present.
        for rank, cand in enumerate(scored_candidates[:5], 1):
            is_top = (rank == 1)
            is_confirmed = is_top and (cand["combined_score"] >= CONFIDENT_THRESHOLD or cand["lexical_score"] >= 0.8)
            navigable = 1 if is_confirmed else 0
            decision = "confirmed_semantic_destination" if is_confirmed else "ranked_alternative"

            evidence = {
                "lemma": lemma,
                "volume": vol,
                "section": sec,
                "rank": rank,
                "lexical_score": cand["lexical_score"],
                "semantic_score": cand["semantic_score"],
                "combined_score": cand["combined_score"],
                "decision": decision,
            }

            results_batch.append((
                iid,
                cand["file"],
                rank,
                cand["semantic_score"],
                cand["lexical_score"],
                cand["combined_score"],
                navigable,
                decision,
                json.dumps(evidence, ensure_ascii=False),
            ))

            if is_confirmed:
                confirmed_destinations += 1
            else:
                alternatives_retained += 1

        if len(results_batch) >= 500:
            cat_cur.executemany(
                """
                INSERT OR REPLACE INTO semantic_reconciliation_results
                (item_id, file, semantic_rank, semantic_score, lexical_score, combined_score, navigable, decision_status, evidence_json)
                VALUES (?,?,?,?,?,?,?,?,?)
                """,
                results_batch,
            )
            cat_conn.commit()
            results_batch = []

    if results_batch:
        cat_cur.executemany(
            """
            INSERT OR REPLACE INTO semantic_reconciliation_results
            (item_id, file, semantic_rank, semantic_score, lexical_score, combined_score, navigable, decision_status, evidence_json)
            VALUES (?,?,?,?,?,?,?,?,?)
            """,
            results_batch,
        )
        cat_conn.commit()

    cat_conn.close()
    emb_conn.close()

    summary = {
        "reconciled_items": reconciled_items,
        "confirmed_destinations": confirmed_destinations,
        "alternatives_retained": alternatives_retained,
        "unresolved_items": unresolved_items,
        "duration_seconds": round(time.time() - t0, 2),
        "policy": {
            "lexical_weight": LEXICAL_WEIGHT,
            "semantic_weight": SEMANTIC_WEIGHT,
            "confident_threshold": CONFIDENT_THRESHOLD,
            "min_alternative_threshold": MIN_ALTERNATIVE_THRESHOLD,
            "promotion_rule": "Confirmed navigable ONLY when combined score >= 0.75 or strong lexical anchor",
        },
    }

    out_report_path.parent.mkdir(parents=True, exist_ok=True)
    out_report_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n")
    print(f"Reconciliation summary saved to {out_report_path}")
    return summary


def main():
    parser = argparse.ArgumentParser(description="Reconcile semantic candidates with onomastic catalog")
    parser.add_argument("--catalog-db", type=Path, default=PROJECT_ROOT / "data/index_catalog/unified_onomastic_catalog_20261110/search.sqlite")
    parser.add_argument("--embeddings-db", type=Path, default=PROJECT_ROOT / "data/index_catalog/qwen_embeddings.sqlite")
    parser.add_argument("--out-report", type=Path, default=PROJECT_ROOT / "data/index_catalog/reconciliation_summary.json")
    parser.add_argument("--limit", type=int, default=None)
    args = parser.parse_args()

    res = reconcile_semantic_candidates(
        catalog_db_path=args.catalog_db,
        embeddings_db_path=args.embeddings_db,
        out_report_path=args.out_report,
        limit=args.limit,
    )
    print(json.dumps(res, indent=2))


if __name__ == "__main__":
    main()
